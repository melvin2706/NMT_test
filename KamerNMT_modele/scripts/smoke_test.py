"""End-to-end smoke test on toy data: corpus -> tokenizer -> train -> evaluate
-> export (CTranslate2 INT8, ONNX INT8) -> benchmark.

The toy data is French/English built from templates, plus "xxa", a FAKE
language made by a reversible rule from the English side. No Cameroonian text
is generated. The point is to check the plumbing, not translation quality.

    python scripts/smoke_test.py            # full run (~ a few minutes on CPU)
    python scripts/smoke_test.py --steps 300
"""

from __future__ import annotations

import argparse
import csv
import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
WORK = ROOT / "work" / "smoke"

SUBJECTS = [  # fr, en, english verb takes -s, fr person index
    ("je", "I", False, 0), ("tu", "you", False, 1), ("il", "he", True, 2), ("elle", "she", True, 2),
    ("nous", "we", False, 3), ("vous", "you", False, 4), ("ils", "they", False, 5),
]
VERBS = {  # fr conjugations (je, tu, il, nous, vous, ils), en base, objects
    "manger": (["mange", "manges", "mange", "mangeons", "mangez", "mangent"], "eat",
               [("le poisson", "the fish"), ("la banane", "the banana"), ("le pain", "the bread")]),
    "voir": (["vois", "vois", "voit", "voyons", "voyez", "voient"], "see",
             [("le marché", "the market"), ("la rivière", "the river"), ("l'école", "the school")]),
    "acheter": (["achète", "achètes", "achète", "achetons", "achetez", "achètent"], "buy",
                [("le poisson", "the fish"), ("la chèvre", "the goat"), ("le maïs", "the maize")]),
    "aimer": (["aime", "aimes", "aime", "aimons", "aimez", "aiment"], "like",
              [("la musique", "the music"), ("le maïs", "the maize"), ("l'école", "the school")]),
}


def elide(word: str, nxt: str) -> str:
    return word[:-1] + "'" if word in ("je", "ne") and nxt[0] in "aeiouéèh" else word + " "


def en_3s(v: str) -> str:
    return v + "s"


def make_sentences():
    rows = []
    for _, (conj, en_v, objs) in VERBS.items():
        for fr_s, en_s, third, k in SUBJECTS:
            v = conj[k]
            for fr_o, en_o in objs:
                aff_fr = f"{elide(fr_s, v)}{v} {fr_o}.".replace("' ", "'")
                aff_en = f"{en_s} {en_3s(en_v) if third else en_v} {en_o}."
                neg_fr = f"{fr_s} {elide('ne', v)}{v} pas {fr_o}.".replace("' ", "'")
                neg_en = f"{en_s} {'does' if third else 'do'} not {en_v} {en_o}."
                q_fr = f"Est-ce que {elide(fr_s, v)}{v} {fr_o} ?".replace("' ", "'")
                q_en = f"{'Does' if third else 'Do'} {en_s} {en_v} {en_o}?"
                rows += [(aff_fr[0].upper() + aff_fr[1:], aff_en[0].upper() + aff_en[1:]),
                         (neg_fr[0].upper() + neg_fr[1:], neg_en[0].upper() + neg_en[1:]), (q_fr, q_en)]
    return rows


def fake_lang(en: str) -> str:
    """Reversible nonsense: reverse word order, map some letters to ɛ/ɔ/ŋ, tone marks."""
    table = str.maketrans({"e": "ɛ", "o": "ɔ", "n": "ŋ", "a": "á"})
    words = en.rstrip("?.").lower().split()
    return " ".join(w.translate(table) for w in reversed(words)) + (" ká?" if en.endswith("?") else " .")


def write_fixture() -> Path:
    WORK.mkdir(parents=True, exist_ok=True)
    tsv = WORK / "toy_parallel.tsv"
    with open(tsv, "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f, delimiter="\t", quoting=csv.QUOTE_NONE, escapechar="\\")
        w.writerow(["src_lang", "tgt_lang", "src_text", "tgt_text", "group"])
        for i, (fr, en) in enumerate(make_sentences()):
            w.writerow(["fr", "en", fr, en, f"g{i}"])
            w.writerow(["en", "xxa", en, fake_lang(en), f"g{i}"])
            w.writerow(["fr", "xxa", fr, fake_lang(en), f"g{i}"])
    (WORK / "sources.yaml").write_text(
        "blocklist: [cameroon-int8, flagship]\n"
        "sources:\n"
        "  - id: smoke-toy\n"
        f"    path: {tsv.relative_to(ROOT).as_posix()}\n"
        "    format: parallel_tsv\n    kind: parallel\n"
        "    origin: generated by scripts/smoke_test.py\n    validated: true\n",
        encoding="utf-8")
    (WORK / "bench.txt").write_text("\n".join(fr for fr, _ in make_sentences()[:60]), encoding="utf-8")
    return tsv


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--steps", type=int, default=None)
    a = ap.parse_args()

    import yaml

    from kamernmt.cli import main as cli

    write_fixture()
    corpus = str((WORK / "corpus").relative_to(ROOT))
    cli(["build-corpus", "--sources", str(WORK / "sources.yaml"), "--out", corpus,
         "--valid-frac", "0.1", "--test-frac", "0.1"])
    cli(["train-tokenizer", "--corpus", corpus, "--out", str(WORK / "tokenizer" / "unigram-400"),
         "--vocab", "400", "--temperature", "1.0"])

    cfg_path = ROOT / "configs" / "smoke.yaml"
    if a.steps:
        cfg = yaml.safe_load(cfg_path.read_text(encoding="utf-8"))
        cfg["train"]["max_steps"] = a.steps
        cfg_path = WORK / "smoke.yaml"
        cfg_path.write_text(yaml.safe_dump(cfg), encoding="utf-8")
    cli(["train", "--config", str(cfg_path)])

    ckpt = str(WORK / "run" / "best.pt")
    cli(["translate", "--model", ckpt, "--src", "fr", "--tgt", "en", "Je mange le poisson.", "Est-ce que tu vois la rivière ?"])
    cli(["evaluate", "--model", ckpt, "--corpus", corpus, "--out", str(WORK / "eval" / "pytorch"), "--beam", "4"])
    results = {"pytorch": json.loads((WORK / "eval" / "pytorch" / "metrics.json").read_text(encoding="utf-8"))}

    if importlib.util.find_spec("ctranslate2"):
        ct2_dir = str(WORK / "ct2-int8")
        cli(["export-ct2", "--checkpoint", ckpt, "--out", ct2_dir, "--quantization", "int8"])
        cli(["evaluate", "--model", ct2_dir, "--corpus", corpus, "--out", str(WORK / "eval" / "ct2-int8")])
        results["ct2-int8"] = json.loads((WORK / "eval" / "ct2-int8" / "metrics.json").read_text(encoding="utf-8"))
        cli(["benchmark", "--model", ct2_dir, "--input", str(WORK / "bench.txt"), "--src", "fr", "--tgt", "en",
             "--out", str(WORK / "bench" / "ct2-int8.json")])
    else:
        print("ctranslate2 not installed: skipping CT2 export")

    if importlib.util.find_spec("onnxruntime"):
        onnx_dir = str(WORK / "onnx")
        cli(["export-onnx", "--checkpoint", ckpt, "--out", onnx_dir])
        cli(["evaluate", "--model", onnx_dir, "--corpus", corpus, "--out", str(WORK / "eval" / "onnx-int8"),
             "--beam", "1", "--precision", "int8"])
        results["onnx-int8"] = json.loads((WORK / "eval" / "onnx-int8" / "metrics.json").read_text(encoding="utf-8"))
    else:
        print("onnxruntime not installed: skipping ONNX export")

    cli(["benchmark", "--model", ckpt, "--input", str(WORK / "bench.txt"), "--src", "fr", "--tgt", "en",
         "--n", "30", "--out", str(WORK / "bench" / "pytorch.json")])

    print("\n=== smoke summary (chrF++ per direction) ===")
    for name, r in results.items():
        print(name, {d: m["chrf++"] for d, m in r["directions"].items()})


if __name__ == "__main__":
    main()
